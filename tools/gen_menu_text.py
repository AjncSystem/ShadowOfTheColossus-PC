# -*- coding: utf-8 -*-
"""Writes gpu/shim/bbport_menu_text.inc: the in-game menu's texts (L("pt", "en") in
gpu/shim/bbport_overlay.cpp) in Spanish, Chinese, Korean and Russian, looked up by the Portuguese
text in the launcher's translations (launcher/sotc_i18n.py) and in MENU_TEXTS below.

    python tools/gen_menu_text.py           # writes the .inc, lists texts without a translation
    python tools/gen_menu_text.py --check   # only lists them (exit 1 when some are missing)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'launcher'))
from sotc_i18n import TRANSLATIONS  # noqa: E402
from menu_texts import MENU_TEXTS  # noqa: E402  (tools/menu_texts.py)

LANGS = ('es', 'zh', 'ko', 'ru')
CALL = re.compile(r'\bL\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)')


def menu_strings():
    source = (ROOT / 'gpu' / 'shim' / 'bbport_overlay.cpp').read_text(encoding='utf-8')
    seen = {}
    for pt, en in CALL.findall(source):
        seen.setdefault(pt, en)
    return seen


def lookup(lang, pt):
    return MENU_TEXTS.get(lang, {}).get(pt) or TRANSLATIONS.get(lang, {}).get(pt) or ''


def c_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    strings = menu_strings()
    missing = [(lang, pt) for pt in strings for lang in LANGS if not lookup(lang, pt)]
    for lang, pt in missing:
        print(f'missing {lang}: {pt}')
    if '--check' in sys.argv:
        return 1 if missing else 0
    lines = ['// Generated by tools/gen_menu_text.py: do not edit.',
             '// clang-format off',
             'static const MenuText kMenuText[] = {']
    for pt in strings:
        values = ', '.join(c_string(lookup(lang, pt)) for lang in LANGS)
        lines.append(f'    {{{c_string(pt)}, {values}}},')
    lines += ['};', '// clang-format on', '']
    out = ROOT / 'gpu' / 'shim' / 'bbport_menu_text.inc'
    out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{out.relative_to(ROOT)}: {len(strings)} texts, {len(missing)} missing translations')
    return 0


if __name__ == '__main__':
    sys.exit(main())
